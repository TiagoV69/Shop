package com.portafolio.shop.shop_api.Config;

import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.OpenAPI;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class OpenApiConfig {

    @Bean
    public OpenAPI customOpenAPI() {
        return new OpenAPI()
                .info(new Info()
                        .title("Tienda Online API")
                        .version("1.0.0")
                        .description("API REST para una tienda online de ejemplo, construida con Spring Boot. Este proyecto demuestra la gestión de productos, usuarios con roles y un sistema de pedidos.")
                        .termsOfService("http://swagger.io/terms/")
                        .license(new License().name("Apache 2.0").url("http://springdoc.org")));
    }
}